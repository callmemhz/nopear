// Identity rewrite of pi's default system prompt. Prompt text only — no request
// headers or client identifiers are touched anywhere.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const PI_IDENTITY = 'You are an expert coding assistant operating inside pi, a coding agent harness.';

const suffixOf = (persona: string): string => `When asked who or what you are, say you are ${persona}.`;

/** Idempotent: rewriting an already-rewritten prompt returns it unchanged (SYSTEM.md is rewritten by
 *  systemPromptOverride and again by the before_agent_start hook). */
export function rewriteSystemPrompt(base: string | undefined, persona: string): string | undefined {
  if (base === undefined) return undefined;
  let out = base.split(PI_IDENTITY).join(`You are ${persona}, an expert coding assistant.`);
  // Drop the "Pi documentation (...):" heading and its "- ..." bullet lines.
  out = out.replace(/\n*Pi documentation[^\n]*(?:\n- [^\n]*)*/g, '');
  const suffix = suffixOf(persona);
  out = out.trimEnd();
  if (out.endsWith(suffix) || out.includes(`\n\n${suffix}\n\n`)) return out;
  return `${out}\n\n${suffix}`;
}

/** Append `extra` (e.g. the PM brain prompt) once; a prompt that already contains it is returned as-is. */
export function appendOnce(prompt: string | undefined, extra: string | undefined): string | undefined {
  if (prompt === undefined || !extra) return prompt;
  if (prompt.includes(extra)) return prompt;
  return `${prompt}\n\n${extra}`;
}

/** Set in the worker process: its own sessions are rewritten by the host, so the generated extension stands down there. */
export const IN_PROCESS_FLAG = '__nopearPersonaInProcess';
export const PERSONA_EXTENSION_FILE = 'nopear-persona.ts';

/**
 * Background subagents run as separate `pi` processes (PI_CODING_AGENT_DIR = the worker's agent dir), so the host's
 * rewrite never reaches them: they would introduce themselves with pi's default identity. This extension, auto-loaded
 * from `<agentDir>/extensions/`, gives them the same prompt rewrite. Self-contained: it must not import the worker.
 */
export function personaExtensionSource(persona: string): string {
  return `// Generated by the NoPear worker on every start; edits are overwritten. Set NOPEAR_PERSONA to change the name.
// Background subagents (separate \`pi\` processes) get the same identity rewrite as the worker's own sessions.
const PERSONA = ${JSON.stringify(persona)};
const PI_IDENTITY = ${JSON.stringify(PI_IDENTITY)};
const SUFFIX = \`When asked who or what you are, say you are \${PERSONA}.\`;

function rewrite(base) {
  let out = base.split(PI_IDENTITY).join(\`You are \${PERSONA}, an expert coding assistant.\`);
  out = out.replace(/\\n*Pi documentation[^\\n]*(?:\\n- [^\\n]*)*/g, '');
  out = out.trimEnd();
  if (out.endsWith(SUFFIX) || out.includes(\`\\n\\n\${SUFFIX}\\n\\n\`)) return out;
  return \`\${out}\\n\\n\${SUFFIX}\`;
}

export default function (pi) {
  if (globalThis[${JSON.stringify(IN_PROCESS_FLAG)}]) return; // the worker rewrites its own sessions
  pi.on('before_agent_start', (e) => (typeof e.systemPrompt === 'string' ? { systemPrompt: rewrite(e.systemPrompt) } : undefined));
}
`;
}

/** Write (or refresh) the subagent persona extension; returns its path, or null when it could not be written. */
export function installPersonaExtension(agentDir: string, persona: string, log: (m: string) => void = (m) => console.warn(m)): string | null {
  const dir = join(agentDir, 'extensions');
  const file = join(dir, PERSONA_EXTENSION_FILE);
  const src = personaExtensionSource(persona);
  try {
    let cur: string | null = null;
    try { cur = readFileSync(file, 'utf8'); } catch { /* missing */ }
    if (cur !== src) {
      mkdirSync(dir, { recursive: true, mode: 0o700 });
      writeFileSync(file, src, { mode: 0o600 });
    }
    return file;
  } catch (err) {
    log(`[nopear] could not write ${file}: ${(err as Error)?.message ?? err} — background subagents keep pi's default identity`);
    return null;
  }
}
